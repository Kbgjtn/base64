#!/usr/bin/env python3
"""Turn bench/results/<tier>-<cpu>/bench.csv files into README Markdown tables.

    python3 scripts/bench-summary.py bench/results > bench/results/SUMMARY.md

Each cell shows our median and, in parentheses, the speedup over std built at
the same -Dcpu. Inputs under 1 KiB are shown as ns/op, since GiB/s at a few
bytes mostly measures call overhead. The std column uses the highest tier
present, labelled with its -Dcpu.
"""

import csv
import glob
import os
import sys

TIER_ORDER = ["scalar", "simd128", "avx2"]
DEFAULT_ROWS = ["random/016-b", "random/032-b", "random/064-b", "random/1-kib",
                "random/64-kib", "random/1-mib", "random/4-mib", "random/64-mib"]
KIND_SIZE = "64-kib"


def load(root):
    rows, metas = [], {}
    for path in sorted(glob.glob(os.path.join(root, "*", "bench.csv"))):
        with open(path, newline="") as f:
            rows += list(csv.DictReader(f))
        meta = os.path.join(os.path.dirname(path), "meta.txt")
        if os.path.exists(meta):
            with open(meta) as f:
                kv = dict(line.rstrip("\n").split(":", 1) for line in f if ":" in line)
            metas[os.path.basename(os.path.dirname(path))] = {k.strip(): v.strip() for k, v in kv.items()}
    return rows, metas


def index(rows):
    return {(r["tier"], r["case"], r["op"], r["codec"]): r for r in rows}


def cell(r, std=False):
    if r is None:
        return "—"
    payload = int(r["payload_bytes"])
    ns = float(r["std_ns_median" if std else "mine_ns_median"])
    gib = float(r["std_gib_s" if std else "mine_gib_s"])
    value = f"{ns:.1f} ns" if payload < 1024 else f"{gib:.2f} GiB/s"
    return value if std else f"{value} ({float(r['speedup']):.2f}×)"


def size_label(case, rows):
    for r in rows:
        if r["case"] == case:
            n = int(r["payload_bytes"])
            if n < 1024:
                return f"{n} B"
            if n < 1 << 20:
                return f"{n >> 10} KiB"
            return f"{n >> 20} MiB"
    return case


def table(idx, rows, tiers, cases, op, codec, first_col):
    std_tier = tiers[-1]
    target = {r["tier"]: r["target_cpu"] for r in rows}
    head = [first_col, f"std ({target[std_tier]})"] + [f"{t} ({target[t]})" for t in tiers]
    out = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    for case, label in cases:
        if not any((t, case, op, codec) in idx for t in tiers):
            continue
        line = [label, cell(idx.get((std_tier, case, op, codec)), std=True)]
        line += [cell(idx.get((t, case, op, codec))) for t in tiers]
        out.append("| " + " | ".join(line) + " |")
    return "\n".join(out)


def main():
    root = sys.argv[1] if len(sys.argv) > 1 else "bench/results"
    rows, metas = load(root)
    if not rows:
        sys.exit(f"no bench.csv under {root}/*/")
    idx = index(rows)
    tiers = [t for t in TIER_ORDER if any(r["tier"] == t for r in rows)]
    all_cases = list(dict.fromkeys(r["case"] for r in rows))

    by_size = [(c, size_label(c, rows)) for c in DEFAULT_ROWS if c in all_cases]
    by_kind = [(c, c.split("/")[0]) for c in all_cases if c.endswith("/" + KIND_SIZE)]
    by_codec_case = f"random/{KIND_SIZE}"

    print("<!-- generated by scripts/bench-summary.py; do not edit by hand -->\n")
    for op, title in (("encode", "Encode"), ("decode", "Decode")):
        print(f"#### {title}, `standard`, random input\n")
        print(table(idx, rows, tiers, by_size, op, "standard", "Input"))
        print()
        print(f"#### {title}, `standard`, {KIND_SIZE.replace('-kib', ' KiB')} by content\n")
        print(table(idx, rows, tiers, by_kind, op, "standard", "Content"))
        print()

    print(f"#### All codecs, {by_codec_case}\n")
    codec_rows = []
    for op in ("encode", "decode"):
        for codec in ("standard", "standard_no_pad", "url_safe", "url_safe_no_pad"):
            codec_rows.append((op, codec))
    std_tier = tiers[-1]
    target = {r["tier"]: r["target_cpu"] for r in rows}
    head = ["Op", "Codec", f"std ({target[std_tier]})"] + [f"{t} ({target[t]})" for t in tiers]
    print("| " + " | ".join(head) + " |")
    print("|" + "---|" * len(head))
    for op, codec in codec_rows:
        if not any((t, by_codec_case, op, codec) in idx for t in tiers):
            continue
        line = [op, f"`{codec}`", cell(idx.get((std_tier, by_codec_case, op, codec)), std=True)]
        line += [cell(idx.get((t, by_codec_case, op, codec))) for t in tiers]
        print("| " + " | ".join(line) + " |")
    print()

    extra = [(op, c) for op in ("decode_ignore", "decode_err_late", "decode_err_pad")
             for c in ("random/1-kib", "random/64-kib")]
    if any((t, c, op, "standard") in idx for t in tiers for op, c in extra):
        print("#### Other decode paths, `standard`\n")
        head = ["Op", "Input", f"std ({target[std_tier]})"] + [f"{t} ({target[t]})" for t in tiers]
        print("| " + " | ".join(head) + " |")
        print("|" + "---|" * len(head))
        for op, c in extra:
            if not any((t, c, op, "standard") in idx for t in tiers):
                continue
            line = [f"`{op}`", size_label(c, rows), cell(idx.get((std_tier, c, op, "standard")), std=True)]
            line += [cell(idx.get((t, c, op, "standard"))) for t in tiers]
            print("| " + " | ".join(line) + " |")
        print()

    print("Cells: our median (speedup vs std at the same `-Dcpu`). GiB/s counts payload (decoded) bytes.\n")
    for name, m in sorted(metas.items()):
        label = f" — {m['label']}" if m.get("label") else ""
        print(f"- `{name}`: {m.get('host_cpu', '?')}{label}; virt {m.get('virt', '?')}; "
              f"governor {m.get('governor', '?')}; zig {m.get('zig', '?')}; {m.get('kernel', '?')}; "
              f"rev {m.get('git_rev', '?')}; {m.get('date_utc', '?')}")


if __name__ == "__main__":
    main()
